`timescale 1ns / 1ps
//////////////////////////////////////////////////////////////////////////////////
// 实验课程: 数字逻辑设计 - 实验2: 触发器与寄存器文件
// 模块名称: testbench (用于 reg8file)
// 功能描述: 寄存器文件仿真测试平台
// 仿真顺序规范 (严格对齐实验要求):
//   1. 初始全局复位: clr=1, 验证初态各寄存器为 8'h00
//   2. 寄存器同步写入:
//      - 写入第 1 个寄存器: 向 Reg[2] 写入 8'hA5 (10100101)
//      - 写入第 2 个寄存器: 向 Reg[5] 写入 8'h3C (00111100)
//   3. 关闭写使能与保持测试: en=0, 改变 d, 验证不产生意外覆盖
//   4. 寄存器异步读取:
//      - 切换 rsel=2, 验证即刻读出 8'hA5 (无需时钟对齐)
//      - 切换 rsel=5, 验证即刻读出 8'h3C
//      - 切换 rsel=0, 验证未写入寄存器保持为 8'h00
//   5. 异步全局清零测试:
//      - 在 rsel=2 且 q=8'hA5 期间，于时钟非上升沿拉高 clr=1, 验证输出 q 立即变为 8'h00
//   6. 清零后再读取验证:
//      - 撤销复位，切换 rsel=5, 验证 Reg[5] 同样被完全清零 (输出 8'h00)
//////////////////////////////////////////////////////////////////////////////////

module testbench ();

reg        clk;
reg        clr;
reg        en;
reg  [7:0] d;
reg  [2:0] wsel;
reg  [2:0] rsel;
wire [7:0] q;

// 生成 100MHz 仿真时钟，周期 10ns
always #5 clk = ~clk;

initial begin
    // --------------------------------------------------------------------------
    // 阶段 1: 初始复位与信号初始化 (0 ~ 15 ns)
    // --------------------------------------------------------------------------
    clk  = 1'b0;
    clr  = 1'b1;
    en   = 1'b0;
    d    = 8'h00;
    wsel = 3'b000;
    rsel = 3'b000;

    #15;
    clr  = 1'b0; // 释放复位信号

    // --------------------------------------------------------------------------
    // 阶段 2: 寄存器写入阶段 (15 ~ 35 ns)
    // 写入第一个寄存器: Reg[2] = 8'hA5
    // --------------------------------------------------------------------------
    #5;
    en   = 1'b1;
    wsel = 3'd2;
    d    = 8'hA5;

    // 写入第二个寄存器: Reg[5] = 8'h3C
    #10;
    wsel = 3'd5;
    d    = 8'h3C;

    // --------------------------------------------------------------------------
    // 阶段 3: 关闭写使能与保持测试 (35 ~ 45 ns)
    // --------------------------------------------------------------------------
    #10;
    en   = 1'b0;
    d    = 8'hFF; // 改变输入数据，验证 en=0 时寄存器不受影响
    wsel = 3'd0;

    // --------------------------------------------------------------------------
    // 阶段 4: 寄存器异步读取阶段 (45 ~ 75 ns)
    // --------------------------------------------------------------------------
    #10;
    rsel = 3'd2; // 读取 Reg[2]，预期即刻输出 8'hA5

    #10;
    rsel = 3'd5; // 读取 Reg[5]，预期即刻输出 8'h3C

    #10;
    rsel = 3'd0; // 读取未写入的 Reg[0]，预期输出 8'h00

    // --------------------------------------------------------------------------
    // 阶段 5: 异步清零测试阶段 (75 ~ 95 ns)
    // 先读出 Reg[2] 使 q 输出 8'hA5，随后拉高 clr，观察 q 是否立即归零
    // --------------------------------------------------------------------------
    #10;
    rsel = 3'd2; // 此时 q 应为 8'hA5

    #7; // 选在时钟下降沿后（82ns），非时钟上升沿触发异步清零
    clr  = 1'b1;

    #13;
    clr  = 1'b0; // 释放清零信号 (95ns)

    // --------------------------------------------------------------------------
    // 阶段 6: 清零后再读取验证阶段 (95 ~ 125 ns)
    // --------------------------------------------------------------------------
    #10;
    rsel = 3'd2; // 再次读 Reg[2]，预期输出 8'h00

    #10;
    rsel = 3'd5; // 再次读 Reg[5]，预期输出 8'h00

    #20;
    $finish;
end

// 实例化寄存器文件待测模块
reg8file u_reg8file (
    .clk (clk),
    .clr (clr),
    .en  (en),
    .d   (d),
    .wsel(wsel),
    .rsel(rsel),
    .q   (q)
);

endmodule
