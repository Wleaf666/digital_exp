`timescale 1ns / 1ps
//////////////////////////////////////////////////////////////////////////////////
// 实验课程: 数字逻辑设计 - 实验2: 触发器与寄存器文件
// 模块名称: dff_tb
// 功能描述: 异步复位、同步使能 D 触发器的仿真测试平台 (Testbench)
// 测试流程:
//   1. 初始复位测试 (0~10ns): clr=1, 验证初态 q=0
//   2. 同步写入测试 (10~40ns): clr=0, en=1, 验证 q 在时钟上升沿跟随输入 d
//   3. 读出保持测试 (40~50ns): en=0, 改变 d, 验证输出 q 保持不变
//   4. 异步清零测试 (50~70ns): 在非时钟边沿拉高 clr, 验证 q 立即异步清零
//////////////////////////////////////////////////////////////////////////////////

module dff_tb ();

reg  clk;
reg  clr;
reg  en;
reg  d;
wire q;

// 100MHz 仿真时钟，周期 10ns
always #5 clk = ~clk;

initial begin
    // 阶段1: 初始复位阶段
    clk = 1'b0;
    clr = 1'b1;
    en  = 1'b0;
    d   = 1'b0;

    // 阶段2: 同步写入测试阶段
    #10;
    clr = 1'b0;
    en  = 1'b1;
    d   = 1'b1;
    #10 d = 1'b0;
    #10 d = 1'b1;

    // 阶段3: 读取保持测试阶段
    #10;
    en = 1'b0;
    d  = 1'b0;

    // 阶段4: 异步清零测试阶段 (选在下降沿附近拉高复位，验证无需等待上升沿)
    #10;
    clr = 1'b1;
    #20;
    clr = 1'b0;

    // 阶段5: 结束仿真
    #30;
    $finish;
end

// 实例化待测模块 (DUT)
dff u_dff (
    .clk(clk),
    .clr(clr),
    .en (en),
    .d  (d),
    .q  (q)
);

endmodule
