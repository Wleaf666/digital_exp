`timescale 1ns / 1ps
//////////////////////////////////////////////////////////////////////////////////
// 实验课程: 数字逻辑设计 - 实验4: 数码管控制器
// 模块名称: testbench
// 功能描述: 数码管控制器系统综合仿真验证平台
//
// 仿真设计与报告截图要求严密对齐:
//   1. 调小分频参数加速仿真:
//      - SCAN_CNT_MAX = 10 : 8 个数码管每个位选持续 10 个时钟周期 (100ns)，完整呈现学号轮询
//      - DEBOUNCE_CNT_MAX = 5 : 消抖滤波时间为 5 个时钟周期 (50ns)，过滤持续小于 50ns 的抖动
//      - TIMER_CNT_MAX = 10 : 0~20 计数器分频步长调小，快速验证
//   2. 顺序覆盖三大实验报告验证目标:
//      - 阶段一 [数码管轮询]: sw0=1，完整呈现 8 个数码管轮询时 led_en、led_cx 与学号 32'h25311308
//      - 阶段二 [按键消抖对比计数]: 模拟两次带有多次高低毛刺的机械抖动，验证无消抖误计与消抖后准确计 2 次
//      - 阶段三 [二级寄存器级联边沿检测]: 观测两级触发器打拍 sig_r0, sig_r1 与 pos_edge 脉冲时序
//////////////////////////////////////////////////////////////////////////////////

module testbench;

    // ---------------- 激励驱动信号 ----------------
    reg clk;
    reg rst;
    reg sw0;
    reg btn_s2;
    reg btn_s3;

    // ---------------- 输出监测信号 ----------------
    wire [7:0] led_en;
    wire [7:0] led_cx;

    // ---------------- 100MHz 系统时钟（周期 10ns） ----------------
    initial clk = 1'b0;
    always #5 clk = ~clk;

    // ---------------- 待测顶层模块实例化 ----------------
    seg_ctrl_top #(
        .SCAN_CNT_MAX    (24'd10), // 每个数码管扫描 10 个时钟周期
        .DEBOUNCE_CNT_MAX(20'd5),  // 消抖时间 5 个时钟周期 (50ns)
        .TIMER_CNT_MAX   (24'd10)  // 定时器快速步进
    ) u_dut (
        .clk   (clk),
        .rst   (rst),
        .sw0   (sw0),
        .btn_s2(btn_s2),
        .btn_s3(btn_s3),
        .led_en(led_en),
        .led_cx(led_cx)
    );

    // ---------------- 层次化引用内部关键信号（便于波形直接观测） ----------------
    wire [31:0] display       = u_dut.current_display;
    wire [7:0]  raw_s3_cnt    = {u_dut.raw_s3_tens, u_dut.raw_s3_ones};
    wire [7:0]  deb_s3_cnt    = {u_dut.deb_s3_tens, u_dut.deb_s3_ones};
    wire [7:0]  timer_20_cnt  = {u_dut.timer_tens, u_dut.timer_ones};
    
    // 边沿检测内部两级级联寄存器信号 (用于报告第二部分截图)
    wire sig_r0   = u_dut.u_edge_s3_raw.sig_r0;
    wire sig_r1   = u_dut.u_edge_s3_raw.sig_r1;
    wire pos_edge = u_dut.u_edge_s3_raw.pos_edge;

    // ---------------- 仿真激励主流程 ----------------
    initial begin
        // 初始化信号
        rst    = 1'b1;
        sw0    = 1'b1; // 先开启模式 1 (学号固定显示)
        btn_s2 = 1'b0;
        btn_s3 = 1'b0;

        // =====================================================================
        // 目标 1: 复位释放与数码管 8 位完整轮询 (0 ~ 900ns)
        // 对应报告第一部分要求：完整体现 8 个数码管轮询位选、段选及学号 32'h25311308
        // =====================================================================
        #25;
        rst = 1'b0; // 释放复位

        // 每个数码管扫描 10 个时钟周期 (100ns)，8 个数码管共计 800ns 走满一个完整周期
        #820;

        // =====================================================================
        // 目标 2: 切换到模式 2，并模拟真实按键抖动测试 (900ns ~ 2000ns)
        // 模拟带抖动按键输入，体现 2 次消抖计数与两级级联边沿检测波形
        // =====================================================================
        sw0 = 1'b0; // 切入多功能模式 2
        #50;

        // ---------- 模拟第 1 次按键 S3 按下 (带机械抖动) ----------
        // 前沿抖动: 持续时间小于 50ns 的多次毛刺
        btn_s3 = 1'b1; #10;
        btn_s3 = 1'b0; #10;
        btn_s3 = 1'b1; #15;
        btn_s3 = 1'b0; #10;
        // 稳态按下: 持续 120ns (大于消抖阈值 50ns)
        btn_s3 = 1'b1; #120;
        // 释放抖动: 释放时的电平弹跳
        btn_s3 = 1'b0; #10;
        btn_s3 = 1'b1; #10;
        btn_s3 = 1'b0; #100; // 彻底释放稳定

        // ---------- 模拟第 2 次按键 S3 按下 (带机械抖动) ----------
        // 前沿抖动
        btn_s3 = 1'b1; #10;
        btn_s3 = 1'b0; #15;
        btn_s3 = 1'b1; #10;
        btn_s3 = 1'b0; #10;
        // 稳态按下: 持续 120ns
        btn_s3 = 1'b1; #120;
        // 释放抖动
        btn_s3 = 1'b0; #10;
        btn_s3 = 1'b1; #10;
        btn_s3 = 1'b0; #100; // 彻底释放稳定

        // =====================================================================
        // 目标 3: 按键 S2 启停控制测试 (2000ns ~ 2400ns)
        // =====================================================================
        #50;
        // 点按 S2 暂停
        btn_s2 = 1'b1; #80;
        btn_s2 = 1'b0; #100;

        // 再次点按 S2 继续
        btn_s2 = 1'b1; #80;
        btn_s2 = 1'b0; #100;

        #100;
        $finish;
    end

endmodule
