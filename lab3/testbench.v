`timescale 1ns / 1ps
//////////////////////////////////////////////////////////////////////////////////
// 实验课程: 数字逻辑设计 - 实验3: 计数器
// 模块名称: testbench (流水灯仿真测试平台)
// 
// 仿真设计与顺序规范 (严格对齐实验要求):
//   1. 调小计数上限参数:
//      - CNT_500HZ 设置为 6  (完整体现 cnt 从 0 计数到 6)
//      - CNT_10HZ  设置为 11 (完整体现 cnt 从 0 计数到 11)
//   2. 顺序仿真测试流程:
//      - 阶段 1 [复位阶段]: rst=1, 验证初态只亮 LED0 (led = 8'b00000001, cnt=0)
//      - 阶段 2 [频率1单灯流水]: 释放复位, freq_ctrl=0, cnt 从 0~6 循环, 驱动 led 单灯左移
//      - 阶段 3 [频率切换]: freq_ctrl 切换为 1, 完整呈现 cnt 从 0~11 变化, 移位周期放缓
//      - 阶段 4 [模式切换]: mode_sel 切换为 1 (双灯模式), 观察 led 转为连续 2 个灯循环流动
//////////////////////////////////////////////////////////////////////////////////

module testbench ();

reg        clk;
reg        rst;
reg        freq_ctrl;
reg        dir_ctrl;
reg        mode_sel;
wire [7:0] led;

// 100MHz 仿真时钟生成，周期 10ns
always #5 clk = ~clk;

// 提取模块内部计数器 cnt，方便仿真波形中直接观察 (设置为 Unsigned Decimal 显示)
wire [23:0] cnt = u_water_led.cnt;

initial begin
    // --------------------------------------------------------------------------
    // 阶段 1: 初始复位阶段 (0 ~ 25 ns)
    // --------------------------------------------------------------------------
    clk       = 1'b0;
    rst       = 1'b1; // 复位有效
    freq_ctrl = 1'b0; // 默认频率 0 (对应 CNT_500HZ = 6)
    dir_ctrl  = 1'b0; // 默认方向: 左移
    mode_sel  = 1'b0; // 默认模式: 单灯模式

    #25;
    rst = 1'b0;       // 释放复位，流水灯开始运行

    // --------------------------------------------------------------------------
    // 阶段 2: 频率 1 单灯左移流动阶段 (25 ~ 350 ns)
    // 此时 freq_ctrl=0，计数器 cnt 在 0~6 之间循环，观察 led 单灯连续左移
    // --------------------------------------------------------------------------
    #300;

    // --------------------------------------------------------------------------
    // 阶段 3: 频率切换阶段 (350 ~ 800 ns)
    // 将 freq_ctrl 切换为 1，计数器上限变为 11，完整呈现 cnt 从 0 到 11 的计数过程
    // --------------------------------------------------------------------------
    freq_ctrl = 1'b1;
    #450;

    // --------------------------------------------------------------------------
    // 阶段 4: 模式切换阶段 (800 ~ 1400 ns)
    // 将 mode_sel 切换为 1 (双灯模式)，观察流水灯转换为连续 2 个灯同时流动
    // --------------------------------------------------------------------------
    mode_sel = 1'b1;
    #600;

    // 仿真结束
    $finish;
end

// 实例化待测流水灯模块 (DUT)，通过参数传递调小计数值以满足实验波形要求
water_led #(
    .CNT_500HZ(24'd6),  // 调小计数值至 6 (0~6 计数)
    .CNT_10HZ (24'd11)  // 调小计数值至 11 (0~11 计数)
) u_water_led (
    .clk      (clk),
    .rst      (rst),
    .freq_ctrl(freq_ctrl),
    .dir_ctrl (dir_ctrl),
    .mode_sel (mode_sel),
    .led      (led)
);

endmodule
